#!/usr/bin/env python3
"""Generate the textured forest world for visual odometry (RTAB-Map) in GPS-denied flight.

Visual odometry needs texture: the plain world (flat-coloured ground and pillars, empty sky) gives
the feature tracker almost nothing. This script writes, next to it in the package:
  models/ego_textures/      procedural textures (ground, pillar bark, walls)
  worlds/ego_forest.sdf     same pillar layout as worlds/ego_forest_plain.sdf, textured, plus
                            textured perimeter walls so the camera always sees features
Run from the package root:  python3 tools/gen_textured_world.py
"""
import os
import xml.etree.ElementTree as ET

import numpy as np
from PIL import Image, ImageDraw

PKG = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEX_MODEL = os.path.join(PKG, 'models', 'ego_textures')
TEX_DIR = os.path.join(TEX_MODEL, 'materials', 'textures')
PLAIN_WORLD = os.path.join(PKG, 'worlds', 'ego_forest_plain.sdf')
OUT_WORLD = os.path.join(PKG, 'worlds', 'ego_forest.sdf')

# Perimeter walls (world frame, metres): the flight area is x 0..26, y -8..8.
X_MIN, X_MAX, Y_MIN, Y_MAX, WALL_H = -6.0, 32.0, -12.0, 12.0, 4.0
rng = np.random.default_rng(42)


def noise(size, octaves=6):
    """Multi-scale value noise in [0, 1]."""
    out = np.zeros((size, size))
    for o in range(octaves):
        n = 2 ** (o + 2)
        g = rng.random((n + 1, n + 1))
        g = np.kron(g, np.ones((size // n + 1, size // n + 1)))[:size, :size]
        out += g / 2 ** o
    out -= out.min()
    return out / out.max()


def blotches(img, count, rmin, rmax, palette):
    d = ImageDraw.Draw(img)
    w, h = img.size
    for _ in range(count):
        x, y, r = rng.integers(0, w), rng.integers(0, h), rng.integers(rmin, rmax)
        c = tuple(int(v) for v in palette[rng.integers(len(palette))])
        if rng.random() < 0.5:
            d.ellipse([x - r, y - r, x + r, y + r], fill=c)
        else:
            d.rectangle([x - r, y - r // 2, x + r, y + r // 2], fill=c)
    return img


def ground_texture(path):
    n = noise(1024)
    base = np.stack([110 + 70 * n, 100 + 60 * n, 70 + 40 * n], axis=-1)       # earth tones
    grit = rng.random((1024, 1024, 1)) * 60 - 30                               # fine gravel
    img = Image.fromarray(np.clip(base + grit, 0, 255).astype(np.uint8))
    blotches(img, 400, 3, 14, [(60, 55, 40), (190, 180, 150), (90, 110, 60), (150, 130, 100)])
    img.save(path)


def bark_texture(path):
    h, w = 1024, 512
    streak = np.repeat(rng.random((1, w // 4)), 4, axis=1)
    streak = np.repeat(streak, h, axis=0)[:, :w]
    n = noise(1024)[:h, :w]
    base = np.stack([90 + 60 * streak + 40 * n, 60 + 40 * streak + 30 * n, 35 + 25 * streak], axis=-1)
    img = Image.fromarray(np.clip(base + rng.random((h, w, 1)) * 40 - 20, 0, 255).astype(np.uint8))
    blotches(img, 120, 4, 22, [(40, 30, 20), (170, 150, 110), (200, 200, 190), (70, 90, 40)])
    img.save(path)


def wall_texture(path):
    h, w = 512, 1024
    img = Image.new('RGB', (w, h), (150, 70, 50))
    d = ImageDraw.Draw(img)
    bh, bw = 32, 96
    for row in range(h // bh + 1):
        off = (row % 2) * bw // 2
        for col in range(-1, w // bw + 1):
            x0, y0 = col * bw + off, row * bh
            c = tuple(int(v) for v in (150, 70, 50) + rng.integers(-35, 35, 3))
            d.rectangle([x0 + 2, y0 + 2, x0 + bw - 2, y0 + bh - 2], fill=c)
    # Distinct colourful marks: give each wall section its own look (helps loop closure).
    blotches(img, 40, 10, 40, [(30, 60, 200), (240, 220, 40), (20, 160, 60), (240, 240, 240),
                               (20, 20, 20), (200, 40, 160)])
    img.save(path)


def pbr(texture):
    """Gazebo ignores the OBJ's .mtl texture; set it as a PBR albedo map (mesh UVs still tile it)."""
    return ('<material><ambient>1 1 1 1</ambient><diffuse>1 1 1 1</diffuse><pbr><metal>'
            f'<albedo_map>model://ego_textures/materials/textures/{texture}</albedo_map>'
            '<metalness>0</metalness><roughness>0.9</roughness></metal></pbr></material>')


def tile(name, x, y, z, sx, sy, sz, texture):
    """Box visual carrying one texture; boxes texture correctly (the OBJ meshes stayed white)."""
    return (f'<visual name="{name}"><pose>{x:.3f} {y:.3f} {z:.3f} 0 0 0</pose>'
            f'<geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry>{pbr(texture)}</visual>')


def main():
    os.makedirs(TEX_DIR, exist_ok=True)
    with open(os.path.join(TEX_MODEL, 'model.config'), 'w') as f:
        f.write('<?xml version="1.0"?>\n<model><name>ego_textures</name><version>1.0</version>'
                '<sdf version="1.9">model.sdf</sdf><description>Procedural textures for the textured '
                'EGO-Planner forest (generated by tools/gen_textured_world.py)</description></model>\n')
    with open(os.path.join(TEX_MODEL, 'model.sdf'), 'w') as f:
        f.write('<?xml version="1.0"?>\n<sdf version="1.9"><model name="ego_textures">'
                '<static>true</static><link name="link"/></model></sdf>\n')
    # Several variants, placed at random, so neighbouring tiles don't repeat exactly
    # (repeated patterns make RTAB-Map's loop closure mistake one place for another).
    for k in range(4):
        ground_texture(os.path.join(TEX_DIR, f'ground_{k}.png'))
        bark_texture(os.path.join(TEX_DIR, f'bark_{k}.png'))
    for k in range(3):
        wall_texture(os.path.join(TEX_DIR, f'wall_{k}.png'))

    tree = ET.parse(PLAIN_WORLD)
    world = tree.getroot().find('world')
    world.set('name', 'ego_forest')
    i = 0
    for m in world.findall('model'):
        name = m.get('name')
        if name.startswith('pillar_'):
            vis = m.find('link/visual')
            vis.remove(vis.find('material'))
            vis.append(ET.fromstring(pbr(f'bark_{i % 4}.png')))
            i += 1
        elif name == 'ground_plane':
            # 4 x 4 m textured tiles over the area around the walls, just above the physics plane.
            link = m.find('link')
            link.remove(link.find('visual'))
            T = 4.0
            for ix, x in enumerate(np.arange(X_MIN - 12, X_MAX + 12, T)):
                for iy, y in enumerate(np.arange(Y_MIN - 12, Y_MAX + 12, T)):
                    link.append(ET.fromstring(tile(f'g_{ix}_{iy}', x + T / 2, y + T / 2, 0.002,
                                                   T, T, 0.004, f'ground_{rng.integers(4)}.png')))
    # Perimeter walls of 4 m panels; one box collision per wall (also an obstacle for the planner).
    walls = {'wall_north': ('x', Y_MAX), 'wall_south': ('x', Y_MIN),
             'wall_west': ('y', X_MIN), 'wall_east': ('y', X_MAX)}
    insert_at = list(world).index(world.find('include'))
    n_panels = 0
    for name, (axis, pos) in walls.items():
        lo, hi = (X_MIN, X_MAX) if axis == 'x' else (Y_MIN, Y_MAX)
        length, c = hi - lo, (lo + hi) / 2
        cx, cy, sx, sy = (c, pos, length, 0.2) if axis == 'x' else (pos, c, 0.2, length)
        panels = []
        for k, a in enumerate(np.arange(lo, hi, 4.0)):
            w = min(4.0, hi - a)
            px, py, psx, psy = ((a + w / 2, pos, w, 0.2) if axis == 'x' else (pos, a + w / 2, 0.2, w))
            panels.append(tile(f'p{k}', px, py, WALL_H / 2, psx, psy, WALL_H, f'wall_{rng.integers(3)}.png'))
        n_panels += len(panels)
        world.insert(insert_at, ET.fromstring(
            f'<model name="{name}"><static>true</static><link name="link">'
            f'<collision name="collision"><pose>{cx} {cy} {WALL_H / 2} 0 0 0</pose>'
            f'<geometry><box><size>{sx} {sy} {WALL_H}</size></box></geometry></collision>'
            + ''.join(panels) + '</link></model>'))
    ET.indent(tree, space='  ')
    header = ('<?xml version="1.0" ?>\n<!-- Textured forest for visual odometry (RTAB-Map). Generated by '
              'tools/gen_textured_world.py from ego_forest_plain.sdf; edit the script, not this file. -->\n')
    with open(OUT_WORLD, 'w') as f:
        f.write(header + ET.tostring(tree.getroot(), encoding='unicode') + '\n')
    print(f'wrote {OUT_WORLD} ({i} textured pillars, {n_panels} wall panels) and {TEX_MODEL}')


if __name__ == '__main__':
    main()
